income = int(input("Monthly allocation: "))
food = int(input("Food expense: "))
travel = int(input("Travel expense: "))
entertainment = int(input("Entertaiment: "))
other = int(input("Other expense: "))
tot_exp = int(food+travel+entertainment+other)
balance = int(income - food - travel- entertainment - other)

print("-----STUDENT MONEY MANAGER-----")
print("Monthly Allocation: ", income)
print("Food Expense      : ", food)
print("Travel Expense    : ", travel)
print("Entertainment     : ", entertainment)
print("Other Expense     : ", other)
print("Total expense     : ", tot_exp)
print("Remaining Balance     : ", balance)
